export function localizeStarterCode(code: string, language: AppLanguage) {
  const reverse = Object.fromEntries(
    Object.entries(codeCommentTranslations).map(([english, chinese]) => [chinese, english]),
  );
  return code.replace(/^(\s*)#\s?(.*)$/gm, (line, indent: string, comment: string) => {
    const translated = language === "zh"
      ? codeCommentTranslations[comment]
      : reverse[comment];
    return translated ? `${indent}# ${translated}` : line;
  });
}

type LanguageContextValue = {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (english: string, chinese?: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

function translateValue(value: string, language: AppLanguage) {
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const core = value.trim();
  if (!core) return value;
  let translated: string | undefined = language === "zh" ? englishToChinese[core] : chineseToEnglish[core];
  if (!translated && language === "zh") {
    translated = core
      .replace(/^Task (\d+)/, "题目 $1")
      .replace(/^Step (\d+)$/, "步骤 $1")
      .replace(/^(\d+) days$/, "$1 天")
      .replace(/^(\d+)% complete$/, "已完成 $1%")
      .replace(/^Example (\d+)$/, "示例 $1")
      .replace(/^(\d+) thinking tasks$/, "$1 道思考题")
      .replace(/^(\d+) of (\d+) completed$/, "已完成 $1 / $2")
      .replace(/^Showing (\d+) of (\d+) beginner tasks$/, "当前显示 $1 / $2 道入门题目")
      .replace(/^Concept:\s*/, "知识点：")
      .replace(/^Briefly describe the main idea you will use for this .+ task\.$/, "简要说明你准备用于这道题的主要思路。")
      .replace(/^Step (\d+) optional$/, "步骤 $1（可选）")
      .replace(/^(\d+)% thinking progress$/, "思考进度 $1%")
      .replace(/^Level (\d+)$/, "等级 $1")
      .replace(/^(\d+) lines$/, "$1 行");
    translated = translated
      .replace(/^(\d+) tasks$/, "$1 道题目")
      .replace(/^(\d+) (day|days)$/, "$1 天");
    if (translated === core) translated = undefined;
  }
  return translated ? `${leading}${translated}${trailing}` : value;
}

function translateDocument(language: AppLanguage) {
  const root = document.body;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    const parent = node.parentElement;
    if (parent && !["SCRIPT", "STYLE", "CODE", "PRE", "TEXTAREA"].includes(parent.tagName)) {
      const next = translateValue(node.nodeValue ?? "", language);
      if (next !== node.nodeValue) node.nodeValue = next;
    }
    node = walker.nextNode();
  }

  root.querySelectorAll<HTMLElement>("[aria-label], [title], [placeholder]").forEach((element) => {
    ["aria-label", "title", "placeholder"].forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, translateValue(value, language));
    });
  });
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === "zh" || saved === "en") setLanguageState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
    translateDocument(language);
    const observer = new MutationObserver(() => translateDocument(language));
    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [language]);

  const setLanguage = useCallback((next: AppLanguage) => {
    window.localStorage.setItem(STORAGE_KEY, next);
    setLanguageState(next);
  }, []);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t: (english, chinese) => language === "zh" ? (chinese ?? englishToChinese[english] ?? english) : english,
  }), [language, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
